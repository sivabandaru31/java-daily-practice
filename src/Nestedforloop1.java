public class Nestedforloop1 {
    public static void main(String[] args) {
        for(int i=0;i<=5;i++){//repersents number of row's
            for(int j=0;j<=5;j++){//repersents number of colomn's
                System.out.print("*"+ " ");
            }
            System.out.println();//line by line
        }
    }
}
